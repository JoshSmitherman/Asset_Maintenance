alter table public.assets add  constraint assets_asset_ref_length
  check (char_length(asset_ref) <= 40);

-- NULL means unassigned; a string of spaces is still rejected.
alter table public.assets drop constraint if exists assets_owner_not_blank;
alter table public.assets add  constraint assets_owner_not_blank
  check (owner_name is null or btrim(owner_name) <> '');

alter table public.assets drop constraint if exists assets_department_not_blank;
alter table public.assets add  constraint assets_department_not_blank
  check (btrim(department) <> '');

alter table public.assets drop constraint if exists assets_device_type_valid;
alter table public.assets add  constraint assets_device_type_valid check (
  device_type in (
    'Laptop', 'Desktop', 'Monitor', 'Docking Station',
    'Phone', 'Tablet', 'Printer', 'Peripheral', 'Other'
  )
);

alter table public.assets drop constraint if exists assets_location_valid;
alter table public.assets add  constraint assets_location_valid check (
  location is null or location in ('Remote', 'Hybrid', 'Office', 'Warehouse')
);

alter table public.assets drop constraint if exists assets_purchase_cost_valid;
