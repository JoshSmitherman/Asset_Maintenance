-- An older database worked out Next Clean Due from Date Cleaned alone. A
-- generated column cannot be edited in place, so it is dropped and re-added
-- with the current rule. Nothing is lost: every value is recalculated from
-- date_cleaned and purchase_date. The view that reads it is rebuilt in
-- section 7 and the index in section 3.
do $$
declare
  current_rule text;
begin
  select pg_get_expr(d.adbin, d.adrelid) into current_rule
  from pg_attrdef d
  join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
  where d.adrelid = 'public.assets'::regclass and a.attname = 'next_clean_due';

  if current_rule is not null and current_rule not like '%purchase_date%' then
    drop view if exists public.assets_with_status;
    alter table public.assets drop column next_clean_due;
    alter table public.assets add column next_clean_due date generated always as (
      case
        when date_cleaned is not null
          then (date_cleaned + make_interval(months => cleaning_interval_months))::date
        when purchase_date is not null
          then (purchase_date + interval '12 months')::date
        else null
      end
    ) stored;
  end if;
end;
$$;

comment on column public.assets.next_clean_due is 'Generated: date_cleaned + cleaning_interval_months, or purchase_date + 12 months if never cleaned. Never written by the client.';


