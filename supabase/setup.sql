alter table public.assets add  constraint assets_cleaned_by_valid
  check (cleaned_by is null or cleaned_by in ('AL', 'BB', 'JS', 'RC', 'TM'));

-- "Cleaned By" and "Date Cleaned" only make sense together.
alter table public.assets drop constraint if exists assets_clean_record_complete;
alter table public.assets add  constraint assets_clean_record_complete check (
  (date_cleaned is null and cleaned_by is null)
  or (date_cleaned is not null and cleaned_by is not null)
);

alter table public.assets drop constraint if exists assets_interval_range;
alter table public.assets add  constraint assets_interval_range
  check (cleaning_interval_months between 1 and 60);

alter table public.assets drop constraint if exists assets_notes_length;
