-- =====================================================================
-- IT Hardware Maintenance Tracker — complete database setup
--
-- ONE script that builds the whole database: tables, generated columns,
-- constraints, indexes, status logic, audit triggers, the cleaning history
-- log, Row Level Security and Realtime.
--
-- HOW TO RUN
--   Supabase Dashboard -> SQL Editor -> New query -> paste all of this ->
--   Run. It should finish with "Success. No rows returned".
--
-- WHEN TO USE IT
--   * A brand-new Supabase project: this is the only script you need. The
--     numbered migration files next to it are the history of how an older
--     database reached this same state; a new one does not need them.
--   * An existing database that has already had schema.sql and migrations
--     001-004 applied: running this changes nothing. It is written to be
--     safe either way.
--
-- IT NEVER DESTROYS DATA. Nothing here drops a table or deletes a row. The
-- only things dropped are the read-only view, policies, triggers and
-- constraints, each recreated immediately afterwards.
--
-- Reference lists (device types, locations, cleaners) are CHECK constraints
-- rather than lookup tables, so a small team can see the whole list at a
-- glance. To change one, edit the constraint here AND src/lib/constants.js.
-- =====================================================================

create extension if not exists pgcrypto;


-- =====================================================================
-- 1. The assets table
-- =====================================================================
create table if not exists public.assets (
  id                       uuid primary key default gen_random_uuid(),

  asset_ref                text not null,
  device_type              text not null,
  -- Nullable on purpose: an asset nobody holds is "unassigned", and blank is
  -- stored as NULL so there is exactly one way to represent "nobody has this".
  owner_name               text,
  department               text not null,

  location                 text,
  purchase_cost            numeric(12, 2),
  purchase_date            date,

  date_cleaned             date,
  cleaned_by               text,
  notes                    text,

  -- Cleaning cadence. Defaults to the 6-month business rule but can be
  -- overridden per asset (e.g. a dusty workshop PC on a 3-month cycle).
  cleaning_interval_months integer not null default 6,

  -- Next Clean Due is STORED and generated by the database, so it can never
  -- drift from Date Cleaned and can be indexed and reported on outside the app.
  next_clean_due date generated always as (
    case
      when date_cleaned is null then null
      else (date_cleaned + make_interval(months => cleaning_interval_months))::date
    end
  ) stored,

  -- Hardware specification. Which of these apply to which device type is the
  -- app's business (src/lib/specs.js); the database only checks they are sane.
  spec_brand               text,
  spec_model               text,
  spec_processor           text,
  spec_ram                 text,
  spec_storage             text,
  spec_screen_size         text,
  spec_battery_type        text,
  spec_charger_type        text,
  spec_resolution          text,
  spec_hdmi_ports          smallint,
  spec_dp_ports            smallint,

  -- Optimistic-concurrency token, bumped by the trigger on every write.
  version                  integer not null default 1,

  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  created_by               uuid references auth.users(id) on delete set null,
  updated_by               uuid references auth.users(id) on delete set null,
  -- Denormalised so the UI can show "last updated by" without reading the
  -- auth schema.
  updated_by_email         text
);

comment on table  public.assets is 'IT hardware assets, their specification and their cleaning history.';
comment on column public.assets.next_clean_due is 'Generated: date_cleaned + cleaning_interval_months. Never written by the client.';
comment on column public.assets.version        is 'Incremented on every write; used for optimistic concurrency control.';
comment on column public.assets.purchase_cost  is 'numeric(12,2), never floating point, so totals do not drift.';
comment on column public.assets.spec_model     is 'Model or variant name, e.g. "Latitude 5540".';

