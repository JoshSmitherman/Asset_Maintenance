-- =====================================================================
-- 4. Cleaning status — the single source of truth, in the database
--
--      Not Tracked   -> anything that is not a laptop or desktop
--      Never Cleaned -> no Date Cleaned and no Purchase Date, so no due date
--      Overdue       -> next_clean_due is in the past
--      Due Soon      -> next_clean_due is within the next 30 days
--      OK            -> more than 30 days remaining
--
--    A monitor is tracked for inventory but never joins the cleaning rota,
--    so it must not be counted as "Never Cleaned".
-- =====================================================================
create or replace function public.asset_status(
  p_device_type    text,
  p_date_cleaned   date,
  p_next_clean_due date
)
returns text
language sql
stable
set search_path = public
as $$
  select case
    when p_device_type not in ('Laptop', 'Desktop')         then 'Not Tracked'
    -- A never-cleaned asset with a purchase date is due a year after
    -- purchase, so it is the due date that decides, not the clean.
    when p_next_clean_due is null                           then 'Never Cleaned'
    when p_next_clean_due < current_date                    then 'Overdue'
    when p_next_clean_due <= current_date + 30              then 'Due Soon'
    else 'OK'
  end;
$$;


-- =====================================================================
-- 5. Write trigger: normalisation, validation and audit stamping.
--    Clients cannot forge created_at, updated_by or version.
-- =====================================================================
create or replace function public.handle_asset_write()
returns trigger
language plpgsql
-- security definer so the stamping works regardless of what the signed-in
-- role may touch in the auth schema. The function only ever rewrites the row
-- being written; it never reads or changes another table.
security definer
set search_path = public, auth, pg_temp
as $$
begin
  new.asset_ref  := btrim(new.asset_ref);
  new.owner_name := nullif(btrim(coalesce(new.owner_name, '')), '');
  new.department := btrim(new.department);
  new.notes      := nullif(btrim(coalesce(new.notes, '')), '');

  new.spec_brand        := nullif(btrim(coalesce(new.spec_brand, '')), '');
  new.spec_model        := nullif(btrim(coalesce(new.spec_model, '')), '');
  new.spec_processor    := nullif(btrim(coalesce(new.spec_processor, '')), '');
  new.spec_ram          := nullif(btrim(coalesce(new.spec_ram, '')), '');
  new.spec_storage      := nullif(btrim(coalesce(new.spec_storage, '')), '');
  new.spec_screen_size  := nullif(btrim(coalesce(new.spec_screen_size, '')), '');
  new.spec_battery_type := nullif(btrim(coalesce(new.spec_battery_type, '')), '');
  new.spec_charger_type := nullif(btrim(coalesce(new.spec_charger_type, '')), '');
  new.spec_resolution   := nullif(btrim(coalesce(new.spec_resolution, '')), '');

  if new.date_cleaned is not null and new.date_cleaned > current_date then
    raise exception 'Date Cleaned cannot be in the future (%).', new.date_cleaned
      using errcode = 'check_violation';
  end if;

  -- Retirement. Anyone may retire kit - it is the safe, reversible way out of
  -- the register - but only an admin may bring it back.
  new.retired_notes := nullif(btrim(coalesce(new.retired_notes, '')), '');

  if new.retired_on is not null and new.retired_on > current_date then
    raise exception 'The retirement date cannot be in the future (%).', new.retired_on
      using errcode = 'check_violation';
  end if;

  if tg_op = 'UPDATE' and old.retired_on is not null and new.retired_on is null
     and not public.is_admin() then
    raise exception 'Only an admin can restore retired kit.'
      using errcode = 'insufficient_privilege';
  end if;

  if new.retired_on is null then
    -- Restored, or never retired: no trace of a retirement left behind.
    new.retired_reason      := null;
    new.retired_notes       := null;
    new.retired_by          := null;
    new.retired_by_email    := null;
    new.data_wiped          := false;
    new.data_wiped_by       := null;
    new.data_wiped_by_email := null;
  elsif tg_op = 'INSERT' or old.retired_on is null then
    -- Who retired it is whoever is signed in, whatever the client says.
    new.retired_by       := auth.uid();
    new.retired_by_email := auth.jwt() ->> 'email';
  else
    new.retired_by       := old.retired_by;
    new.retired_by_email := old.retired_by_email;
  end if;

  -- Who wiped it is chosen from the team; the email is looked up rather than
  -- trusted from the client, so it always matches a real account.
  if not new.data_wiped then
    new.data_wiped_by       := null;
    new.data_wiped_by_email := null;
  elsif new.data_wiped_by is not null then
    select u.email into new.data_wiped_by_email from auth.users u where u.id = new.data_wiped_by;
  end if;

  if tg_op = 'INSERT' then
    new.created_at := now();
    new.created_by := auth.uid();
    new.version    := 1;
  else
    -- Preserve creation audit data regardless of what the client sent.
    new.created_at := old.created_at;
    new.created_by := old.created_by;
    new.version    := old.version + 1;
  end if;

  new.updated_at       := now();
  new.updated_by       := auth.uid();
  new.updated_by_email := coalesce(auth.jwt() ->> 'email', new.updated_by_email);

  return new;
end;
$$;

drop trigger if exists assets_write_trigger on public.assets;
create trigger assets_write_trigger
  before insert or update on public.assets
  for each row execute function public.handle_asset_write();


-- =====================================================================
-- 6. Cleaning history
--    The assets table holds only each asset's MOST RECENT clean: recording
--    a new one overwrites the last. This log keeps every clean, so "how many
--    machines did we clean in September" is answerable at all.
--
--    asset_ref is copied in rather than looked up, so history survives an
--    asset being renamed or retired. Deleting an asset keeps its cleaning
--    record, with asset_id set to null.
-- =====================================================================
create table if not exists public.cleaning_log (
  id              uuid primary key default gen_random_uuid(),
  asset_id        uuid references public.assets(id) on delete set null,
  asset_ref       text not null,
  device_type     text,
  cleaned_on      date not null,
  cleaned_by      text not null,
  logged_at       timestamptz not null default now(),
  logged_by       uuid references auth.users(id),
  logged_by_email text
);

comment on table public.cleaning_log is 'Append-only record of every clean. Written by trigger, never by the app.';

-- Removing an account must not be blocked by the cleans it logged: the log
-- keeps the email, and only the link to the account goes.
alter table public.cleaning_log drop constraint if exists cleaning_log_logged_by_fkey;
alter table public.cleaning_log add  constraint cleaning_log_logged_by_fkey
  foreign key (logged_by) references auth.users(id) on delete set null;

-- One clean per asset per day per person: recording the same clean twice is
-- the same event, and this makes the backfill below safe to re-run.
create unique index if not exists cleaning_log_unique_event
  on public.cleaning_log (asset_id, cleaned_on, cleaned_by);

create index if not exists cleaning_log_cleaned_on_idx on public.cleaning_log (cleaned_on desc);
create index if not exists cleaning_log_asset_ref_idx  on public.cleaning_log (asset_ref);

-- Fires only when the clean itself changes: editing an asset's location or
-- cost must not create a duplicate history entry.
create or replace function public.log_asset_clean()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if new.date_cleaned is null or new.cleaned_by is null then
    return null;
  end if;

  if tg_op = 'UPDATE'
     and new.date_cleaned is not distinct from old.date_cleaned
     and new.cleaned_by   is not distinct from old.cleaned_by then
    return null;
  end if;

  insert into public.cleaning_log
    (asset_id, asset_ref, device_type, cleaned_on, cleaned_by, logged_by, logged_by_email)
  values
    (new.id, new.asset_ref, new.device_type, new.date_cleaned, new.cleaned_by,
     auth.uid(), auth.jwt() ->> 'email')
  on conflict (asset_id, cleaned_on, cleaned_by) do nothing;

  return null;
end;
$$;

drop trigger if exists assets_log_clean on public.assets;
create trigger assets_log_clean
  after insert or update on public.assets
  for each row execute function public.log_asset_clean();

-- Seed the log from whatever the register already holds, so it is not empty
-- on day one. On a new database this finds nothing and does nothing.
insert into public.cleaning_log (asset_id, asset_ref, device_type, cleaned_on, cleaned_by)
select a.id, a.asset_ref, a.device_type, a.date_cleaned, a.cleaned_by
from public.assets a
where a.date_cleaned is not null and a.cleaned_by is not null
on conflict (asset_id, cleaned_on, cleaned_by) do nothing;


-- =====================================================================
-- 6b. Asset history
--     Who has had each asset, and where it has been. One row per change to
--     the user, department, location, device type or reference, written by
--     trigger so it records every change however it was made - one edit, or
--     a bulk reassignment. Cleans are not repeated here: the timeline reads
--     them from cleaning_log.
--
--     History starts the day this section first runs. Assets that already
--     exist get one "tracking_started" row recording who had them then.
-- =====================================================================
create table if not exists public.asset_events (
  id           uuid primary key default gen_random_uuid(),
  asset_id     uuid references public.assets(id) on delete set null,
  asset_ref    text not null,
  event_type   text not null,
  old_value    text,
  new_value    text,
  -- For created / tracking_started: who, where and which department then.
  details      jsonb,
  happened_at  timestamptz not null default now(),
  actor_id     uuid references auth.users(id) on delete set null,
  actor_email  text
);

comment on table public.asset_events is 'Append-only change history per asset. Written by trigger, never by the app.';

alter table public.asset_events drop constraint if exists asset_events_type_valid;
alter table public.asset_events add  constraint asset_events_type_valid check (
  event_type in ('created', 'tracking_started', 'owner', 'department', 'location', 'device_type', 'asset_ref',
                 'retired', 'restored')
);

create index if not exists asset_events_asset_idx on public.asset_events (asset_id, happened_at);

create or replace function public.log_asset_change()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  who_id    uuid := auth.uid();
  who_email text := auth.jwt() ->> 'email';
begin
  if tg_op = 'INSERT' then
    insert into public.asset_events (asset_id, asset_ref, event_type, details, actor_id, actor_email)
    values (new.id, new.asset_ref, 'created',
            jsonb_build_object('owner', new.owner_name, 'department', new.department, 'location', new.location),
            who_id, who_email);
    return null;
  end if;

  if new.owner_name is distinct from old.owner_name then
    insert into public.asset_events (asset_id, asset_ref, event_type, old_value, new_value, actor_id, actor_email)
    values (new.id, new.asset_ref, 'owner', old.owner_name, new.owner_name, who_id, who_email);
  end if;
  if new.department is distinct from old.department then
    insert into public.asset_events (asset_id, asset_ref, event_type, old_value, new_value, actor_id, actor_email)
    values (new.id, new.asset_ref, 'department', old.department, new.department, who_id, who_email);
  end if;
  if new.location is distinct from old.location then
    insert into public.asset_events (asset_id, asset_ref, event_type, old_value, new_value, actor_id, actor_email)
    values (new.id, new.asset_ref, 'location', old.location, new.location, who_id, who_email);
  end if;
  if new.device_type is distinct from old.device_type then
    insert into public.asset_events (asset_id, asset_ref, event_type, old_value, new_value, actor_id, actor_email)
    values (new.id, new.asset_ref, 'device_type', old.device_type, new.device_type, who_id, who_email);
  end if;
  if new.asset_ref is distinct from old.asset_ref then
    insert into public.asset_events (asset_id, asset_ref, event_type, old_value, new_value, actor_id, actor_email)
    values (new.id, new.asset_ref, 'asset_ref', old.asset_ref, new.asset_ref, who_id, who_email);
  end if;
  if old.retired_on is null and new.retired_on is not null then
    insert into public.asset_events (asset_id, asset_ref, event_type, details, actor_id, actor_email)
    values (new.id, new.asset_ref, 'retired',
            jsonb_build_object('retired_on', new.retired_on, 'reason', new.retired_reason,
                               'notes', new.retired_notes, 'data_wiped', new.data_wiped,
                               'data_wiped_by', new.data_wiped_by_email),
            who_id, who_email);
  end if;
  if old.retired_on is not null and new.retired_on is null then
    insert into public.asset_events (asset_id, asset_ref, event_type, actor_id, actor_email)
    values (new.id, new.asset_ref, 'restored', who_id, who_email);
  end if;

  return null;
end;
$$;

